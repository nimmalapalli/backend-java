    // ============================================================
    // CATEGORY UPDATE
    // ============================================================

    private void category(
            String id,
            T translation) {

        categoryRepository.findByNameIgnoreCase(translation.en()).ifPresentOrElse(
                category -> {

                    category.setNameTranslations(
                            translation.toMap()
                    );

                    categoryRepository.save(category);

                    categoriesUpdated++;

                    System.out.println(
                            "CATEGORY UPDATED: "
                                    + category.getName()
                                    + " [" + id + "]"
                    );
                },
                () -> System.out.println(
                        "CATEGORY NOT FOUND: " + translation.en()
                )
        );
    }

    // ============================================================
    // PRODUCT UPDATE
    // ============================================================

    private void product(
            String id,
            T name,
            T description) {

        productRepository.findByNameIgnoreCase(name.en()).ifPresentOrElse(
                product -> {

                    product.setNameTranslations(
                            name.toMap()
                    );

                    product.setDescriptionTranslations(
                            description.toMap()
                    );

                    productRepository.save(product);

                    productsUpdated++;

                    System.out.println(
                            "PRODUCT UPDATED : "
                                    + product.getName()
                                    + " [" + id + "]"
                    );
                },
                () -> System.out.println(
                        "PRODUCT NOT FOUND : " + name.en()
                )
        );
    }

    // ============================================================
    // TRANSLATION RECORD
    // ============================================================

    private record T(
            String en,
            String te,
            String ta,
            String kn,
            String hi
    ) {

        Map<String, String> toMap() {

            Map<String, String> map =
                    new LinkedHashMap<>();

            map.put("en", en);
            map.put("te", te);
            map.put("ta", ta);
            map.put("kn", kn);
            map.put("hi", hi);

            return map;
        }
    }
